/// A server on the Anthropic profile (its endpoint scripted): with the key unset a check is
/// refused `not_ready` naming the credential and its estimate is refused for readiness; with the
/// key set, a 401 during a run ends it `credential`.
#[test]
fn the_served_credential_fixtures_are_what_squint_serves() {
    let anthropic = [
        "provider.profile=anthropic",
        "provider.model=claude-haiku-5-5",
    ];
    let unready_out = out("not-ready");
    let mut command = server(&unready_out, &script("held.json"), &anthropic);
    command.env_remove("ANTHROPIC_API_KEY");
    let mut c = start(&mut command);
    let session = session_id(&mut c);
    let not_ready = refusal(c.call("source_fidelity", pair()));
    assert_eq!(not_ready["reason"], "not_ready", "{not_ready}");
    check(
        "refusal-not-ready.json",
        REFUSAL,
        &fix(&not_ready, &unready_out, &session, &[]),
    );
    let unready = estimate(&mut c, pair());
    assert_eq!(unready["refused"], "readiness", "{unready}");
    check(
        "estimate-refused-readiness.json",
        ESTIMATE_SCHEMA,
        &fix(&unready, &unready_out, &session, &[]),
    );

    let dir = out("credential");
    std::fs::create_dir_all(&dir).unwrap();
    let rejecting = dir.join("script.json");
    std::fs::write(
        &rejecting,
        r#"[{"error": {"status": 401, "message": "invalid x-api-key"}}]"#,
    )
    .unwrap();
    let runs = dir.join("runs");
    let mut command = server(&runs, &rejecting, &anthropic);
    command.env("ANTHROPIC_API_KEY", "sk-fixture-not-a-key");
    let mut c = start(&mut command);
    let session = session_id(&mut c);
    let r = c
        .call("source_fidelity", pair())
        .unwrap()
        .structured
        .unwrap();
    assert_eq!(r["error"]["code"], "credential", "{r}");
    let fixed = run(&r, &runs, &session, "credential", None);
    assert!(!fixed.to_string().contains("sk-fixture-not-a-key"));
    check("run-credential.json", RESULT, &fixed);
}

/// The configuration a host would write where an unconfigured squint looks for it.
const LOOKUP: &str = "/home/user/.config";

/// An unconfigured server cannot price a call: its estimate is refused for readiness with the
/// worst case, the model and the configuration's identity null (4.5). The command line's estimate
/// has no session: `session_id` and `session` null.
#[test]
fn the_unconfigured_and_command_line_estimates_are_what_squint_emits() {
    let dir = out("unconfigured");
    for sub in ["work", "xdg", "home"] {
        std::fs::create_dir_all(dir.join(sub)).unwrap();
    }
    let mut command = Command::new(env!("CARGO_BIN_EXE_squint"));
    command
        .current_dir(dir.join("work"))
        .arg("serve")
        .env("XDG_CONFIG_HOME", dir.join("xdg"))
        .env("HOME", dir.join("home"));
    let mut c = start(&mut command);
    let session = session_id(&mut c);
    let unpriced = estimate(&mut c, pair());
    assert_eq!(unpriced["worst_case_usd"], Value::Null, "{unpriced}");
    let xdg = dir.join("xdg");
    let names = [
        (
            xdg.canonicalize().unwrap().display().to_string(),
            LOOKUP.into(),
        ),
        (xdg.display().to_string(), LOOKUP.into()),
    ];
    check(
        "estimate-refused-readiness-unconfigured.json",
        ESTIMATE_SCHEMA,
        &fix(&unpriced, &dir.join("runs"), &session, &names),
    );

    let cli = Command::new(env!("CARGO_BIN_EXE_squint"))
        .current_dir(repo_root())
        .args([
            "estimate",
            "--json",
            "--config",
            "fixtures/config/minimal.toml",
            "--provider-script",
            "fixtures/scripts/held.json",
            "--use-case",
            "source-fidelity",
            "--candidate",
            "fixtures/images/candidate-64x48.png",
            "--source",
            "fixtures/images/source-64x48.png",
        ])
        .output()
        .unwrap();
    assert_eq!(
        cli.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&cli.stderr)
    );
    let cli: Value = serde_json::from_slice(&cli.stdout).unwrap();
    assert_eq!(cli["session_id"], Value::Null, "{cli}");
    check(
        "estimate-cli.json",
        ESTIMATE_SCHEMA,
        &fix(&cli, &dir.join("runs"), "", &[]),
    );
}

/// `dir`, canonical and as given, written `to` in a fixture: the pairs `fix` replaces.
fn named(dir: &Path, to: &str) -> Vec<(String, String)> {
    let mut names = Vec::new();
    if let Ok(canonical) = dir.canonicalize() {
        names.push((canonical.display().to_string(), to.to_string()));
    }
    names.push((dir.display().to_string(), to.to_string()));
    names
}

/// The path rule (table-manners 5.2) from a served check, each refusal `invalid`, `input`, with
/// its invocation null (its arguments did not resolve): a path outside the allowed directory, a
/// `..` escape, a symlink that points out, a missing file (refused in the same words as the
/// existing one outside, never "not found"), and any path under a server started with no
/// `--allow-dir`, whose session lists `allowed_dirs: []`; the estimate of a call with a path
/// outside, refused `invalid_arguments` (`input`); and a server whose `[serve] allow_dirs` narrows
/// its `--allow-dir` to a subdirectory (`session-narrowed.json`, `/allowed/sub`). The scratch
/// layout's directories are written `/allowed` and `/outside`.
#[test]
fn the_path_rule_fixtures_are_what_squint_serves() {
    let base = out("paths");
    let allowed = base.join("allowed");
    let outside = base.join("outside");
    std::fs::create_dir_all(allowed.join("sub")).unwrap();
    std::fs::create_dir_all(&outside).unwrap();
    for name in ["candidate-64x48.png", "source-64x48.png"] {
        std::fs::copy(
            repo_root().join("fixtures/images").join(name),
            allowed.join(name),
        )
        .unwrap();
    }
    std::fs::copy(
        repo_root().join("fixtures/images/candidate-64x48.png"),
        outside.join("candidate-64x48.png"),
    )
    .unwrap();
    #[cfg(unix)]
    std::os::unix::fs::symlink(
        outside.join("candidate-64x48.png"),
        allowed.join("escape.png"),
    )
    .unwrap();
    let mut names = named(&allowed, "/allowed");
    names.extend(named(&outside, "/outside"));
    let with_candidate = |candidate: PathBuf| {
        json!({
            "candidate": { "path": candidate },
            "source": { "path": allowed.join("source-64x48.png") },
        })
    };

    let runs = base.join("runs");
    let mut command = server(&runs, &script("held.json"), &[]);
    command.arg("--allow-dir").arg(&allowed);
    let mut c = Client::start(&mut command).unwrap();
    let session = session_id(&mut c);
    let mut reasons = Vec::new();
    for (case, candidate) in [
        ("path-outside", outside.join("candidate-64x48.png")),
        (
            "path-dotdot",
            allowed.join("../outside/candidate-64x48.png"),
        ),
        ("path-symlink", allowed.join("escape.png")),
        ("path-missing", outside.join("missing.png")),
    ] {
        let r = c
            .call("source_fidelity", with_candidate(candidate))
            .unwrap()
            .structured
            .unwrap();
        assert_eq!(r["status"], "invalid", "{case}: {r}");
        assert_eq!(r["error"]["code"], "input", "{case}: {r}");
        assert!(r["invocation"].is_null(), "{case}: {r}");
        let mut case_names = vec![(r["run"]["id"].as_str().unwrap().to_string(), case.into())];
        case_names.extend(names.iter().cloned());
        let fixed = fix(&r, &runs, &session, &case_names);
        reasons.push(fixed["error"]["reason"].as_str().unwrap().to_string());
        check(&format!("run-{case}.json"), RESULT, &fixed);
    }
    // Every escape and the missing file read the same, but for the path each names.
    let generic: Vec<String> = reasons
        .iter()
        .map(|r| r.split_once(" is ").unwrap().1.to_string())
        .collect();
    assert!(generic.iter().all(|g| g == &generic[0]), "{reasons:?}");
    assert!(
        !reasons.iter().any(|r| r.contains("not found")),
        "{reasons:?}"
    );

    let refused = refusal(c.call(
        "estimate",
        json!({
            "action": "source_fidelity",
            "arguments": with_candidate(outside.join("candidate-64x48.png")),
        }),
    ));
    assert_eq!(refused["reason"], "invalid_arguments", "{refused}");
    assert_eq!(refused["error"]["code"], "input", "{refused}");
    check(
        "refusal-invalid-arguments-path-outside.json",
        REFUSAL,
        &fix(&refused, &runs, &session, &names),
    );

    let bare_runs = base.join("bare");
    let mut bare = Client::start(&mut server(&bare_runs, &script("held.json"), &[])).unwrap();
    let bare_session = session_id(&mut bare);
    let state: Value =
        serde_json::from_str(&bare.read_resource("squint://session").unwrap()).unwrap();
    assert_eq!(state["allowed_dirs"], json!([]), "{state}");
    check(
        "session-no-allow-dir.json",
        SESSION_SCHEMA,
        &fix(&state, &bare_runs, &bare_session, &names),
    );
    let r = bare
        .call(
            "source_fidelity",
            with_candidate(allowed.join("candidate-64x48.png")),
        )
        .unwrap()
        .structured
        .unwrap();
    assert_eq!(r["status"], "invalid", "{r}");
    assert_eq!(r["error"]["code"], "input", "{r}");
    let mut bare_names = vec![(
        r["run"]["id"].as_str().unwrap().to_string(),
        "path-no-allow-dir".to_string(),
    )];
    bare_names.extend(names.iter().cloned());
    check(
        "run-path-no-allow-dir.json",
        RESULT,
        &fix(&r, &bare_runs, &bare_session, &bare_names),
    );

    let narrowed_runs = base.join("narrowed");
    let narrowing = format!("serve.allow_dirs=[{:?}]", allowed.join("sub"));
    let mut command = server(&narrowed_runs, &script("held.json"), &[&narrowing]);
    command.arg("--allow-dir").arg(&allowed);
    let mut narrowed = Client::start(&mut command).unwrap();
    let narrowed_session = session_id(&mut narrowed);
    let state: Value =
        serde_json::from_str(&narrowed.read_resource("squint://session").unwrap()).unwrap();
    let fixed = fix(&state, &narrowed_runs, &narrowed_session, &names);
    assert_eq!(fixed["allowed_dirs"], json!(["/allowed/sub"]), "{fixed}");
    check("session-narrowed.json", SESSION_SCHEMA, &fixed);
}

/// `squint call` (table-manners 4.8, 4.9) from the command line, offline on the scripted provider:
/// `run-call.json`, the call of `run-completed.json`'s invocation with a `path` beside each image's
/// `expect`; `bundle-check/`, an invocation bundle of that run (its manifest and its two input
/// members, the testkit writer's), and `run-bundle-replay.json`, its replay by `squint call
/// --bundle` from a copy in a fresh directory, from another working directory. Both record the
/// original's invocation exactly: it carries nothing of the machine, so it is kept as squint
/// wrote it (the other machine values are fixed as in every served fixture).
#[test]
fn the_call_and_bundle_fixtures_are_what_squint_emits() {
    let fixtures = repo_root().join("fixtures/contract/squint");
    let completed: Value = serde_json::from_str(
        &std::fs::read_to_string(fixtures.join("run-completed.json")).unwrap(),
    )
    .unwrap();
    let invocation = completed["invocation"].clone();
    assert_eq!(invocation["action"], "source_fidelity", "{invocation}");
    let base = out("call");
    let elsewhere = base.join("elsewhere");
    std::fs::create_dir_all(&elsewhere).unwrap();
    let images = repo_root().join("fixtures/images");
    // What `run-completed.json` ran: the fake tool's configuration and the held verdict.
    let squint = |args: &[&std::ffi::OsStr]| {
        let o = Command::new(env!("CARGO_BIN_EXE_squint"))
            .current_dir(&elsewhere)
            .env("XDG_CACHE_HOME", base.join("cache"))
            .arg("call")
            .args(args)
            .arg("--config")
            .arg(repo_root().join("fixtures/config/fake-tool.toml"))
            .arg("--provider-script")
            .arg(script("held.json"))
            .arg("--out")
            .arg(base.join("runs"))
            .output()
            .unwrap();
        assert_eq!(
            o.status.code(),
            Some(0),
            "{}",
            String::from_utf8_lossy(&o.stderr)
        );
        let r: Value = serde_json::from_slice(&o.stdout).unwrap();
        valid(RESULT, &r);
        assert_eq!(r["status"], "completed", "{r}");
        assert_eq!(r["invocation"], invocation, "the original's invocation");
        r
    };
    let held = |r: &Value, name: &str| {
        let mut fixed = run(r, &base.join("runs"), "", name, None);
        fixed["invocation"] = invocation.clone();
        fixed
    };

    let mut arguments = invocation["arguments"].clone();
    for (slot, file) in [
        ("candidate", "candidate-64x48.png"),
        ("source", "source-64x48.png"),
    ] {
        arguments[slot]["path"] = json!(images.join(file));
    }
    let file = base.join("arguments.json");
    std::fs::write(&file, arguments.to_string()).unwrap();
    let called = squint(&[
        "source_fidelity".as_ref(),
        "--arguments".as_ref(),
        file.as_os_str(),
        "--allow-dir".as_ref(),
        images.as_os_str(),
    ]);
    check("run-call.json", RESULT, &held(&called, "call"));

    let candidate = std::fs::read(images.join("candidate-64x48.png")).unwrap();
    let source = std::fs::read(images.join("source-64x48.png")).unwrap();
    let (step, members) = squint_testkit::bundle::step_from_run(&completed, &[&candidate, &source]);
    let manifest = squint_testkit::bundle::manifest(vec![step]);
    let bundle = fixtures.join("bundle-check");
    if std::env::var_os("UPDATE_CONTRACT_FIXTURES").is_some() {
        let _ = std::fs::remove_dir_all(&bundle);
        squint_testkit::bundle::write_dir(&bundle, &manifest, &members);
    }
    let mut want: Vec<(String, Vec<u8>)> = members.clone();
    want.push(("invocation.json".into(), manifest.clone()));
    want.sort();
    let mut held_files: Vec<(String, Vec<u8>)> = Vec::new();
    for entry in walkdir(&bundle) {
        let name = entry
            .strip_prefix(&bundle)
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/");
        held_files.push((name, std::fs::read(&entry).unwrap()));
    }
    held_files.sort();
    assert!(
        held_files == want,
        "{} drifted from what squint's bundle writer makes of run-completed.json; review, then \
         UPDATE_CONTRACT_FIXTURES=1 and copy to table-manners",
        bundle.display()
    );

    // The committed directory, copied to a fresh place: no original run directory, no image file
    // of the call's, nothing but the bundle.
    let moved = base.join("moved");
    let copy = moved.join("bundle-check");
    for (name, bytes) in &held_files {
        let path = copy.join(name);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, bytes).unwrap();
    }
    let replayed = squint(&[
        "--bundle".as_ref(),
        copy.as_os_str(),
        "--allow-dir".as_ref(),
        moved.as_os_str(),
    ]);
    check(
        "run-bundle-replay.json",
        RESULT,
        &held(&replayed, "bundle-replay"),
    );
}

/// Every file under `dir`, recursively.
fn walkdir(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = std::fs::read_dir(dir) else {
        return out;
    };
    for entry in entries {
        let path = entry.unwrap().path();
        if path.is_dir() {
            out.extend(walkdir(&path));
        } else {
            out.push(path);
        }
    }
    out
}
