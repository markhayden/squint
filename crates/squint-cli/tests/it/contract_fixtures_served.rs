/// A server on the Anthropic profile (its endpoint scripted): with the key unset a check is
/// refused `not_ready` naming the credential and its estimate is refused for readiness; with the
/// key set, a 401 during a run ends it `credential`.
#[test]
fn the_served_credential_fixtures_are_what_squint_serves() {
    let anthropic = [
        "provider.profile=anthropic",
        "provider.model=claude-haiku-5-5",
    ];
    let unready_out = out("not-ready");
    let mut command = server(&unready_out, &script("held.json"), &anthropic);
    command.env_remove("ANTHROPIC_API_KEY");
    let mut c = start(&mut command);
    let session = session_id(&mut c);
    let not_ready = refusal(c.call("source_fidelity", pair()));
    assert_eq!(not_ready["reason"], "not_ready", "{not_ready}");
    check(
        "refusal-not-ready.json",
        REFUSAL,
        &fix(&not_ready, &unready_out, &session, &[]),
    );
    let unready = estimate(&mut c, pair());
    assert_eq!(unready["refused"], "readiness", "{unready}");
    check(
        "estimate-refused-readiness.json",
        ESTIMATE_SCHEMA,
        &fix(&unready, &unready_out, &session, &[]),
    );

    let dir = out("credential");
    std::fs::create_dir_all(&dir).unwrap();
    let rejecting = dir.join("script.json");
    std::fs::write(
        &rejecting,
        r#"[{"error": {"status": 401, "message": "invalid x-api-key"}}]"#,
    )
    .unwrap();
    let runs = dir.join("runs");
    let mut command = server(&runs, &rejecting, &anthropic);
    command.env("ANTHROPIC_API_KEY", "sk-fixture-not-a-key");
    let mut c = start(&mut command);
    let session = session_id(&mut c);
    let r = c
        .call("source_fidelity", pair())
        .unwrap()
        .structured
        .unwrap();
    assert_eq!(r["error"]["code"], "credential", "{r}");
    let fixed = run(&r, &runs, &session, "credential", None);
    assert!(!fixed.to_string().contains("sk-fixture-not-a-key"));
    check("run-credential.json", RESULT, &fixed);
}

/// The configuration a host would write where an unconfigured squint looks for it.
const LOOKUP: &str = "/home/user/.config";

/// An unconfigured server cannot price a call: its estimate is refused for readiness with the
/// worst case, the model and the configuration's identity null (4.5). The command line's estimate
/// has no session: `session_id` and `session` null.
#[test]
fn the_unconfigured_and_command_line_estimates_are_what_squint_emits() {
    let dir = out("unconfigured");
    for sub in ["work", "xdg", "home"] {
        std::fs::create_dir_all(dir.join(sub)).unwrap();
    }
    let mut command = Command::new(env!("CARGO_BIN_EXE_squint"));
    command
        .current_dir(dir.join("work"))
        .arg("serve")
        .env("XDG_CONFIG_HOME", dir.join("xdg"))
        .env("HOME", dir.join("home"));
    let mut c = start(&mut command);
    let session = session_id(&mut c);
    let unpriced = estimate(&mut c, pair());
    assert_eq!(unpriced["worst_case_usd"], Value::Null, "{unpriced}");
    let xdg = dir.join("xdg");
    let names = [
        (
            xdg.canonicalize().unwrap().display().to_string(),
            LOOKUP.into(),
        ),
        (xdg.display().to_string(), LOOKUP.into()),
    ];
    check(
        "estimate-refused-readiness-unconfigured.json",
        ESTIMATE_SCHEMA,
        &fix(&unpriced, &dir.join("runs"), &session, &names),
    );

    let cli = Command::new(env!("CARGO_BIN_EXE_squint"))
        .current_dir(repo_root())
        .args([
            "estimate",
            "--json",
            "--config",
            "fixtures/config/minimal.toml",
            "--provider-script",
            "fixtures/scripts/held.json",
            "--use-case",
            "source-fidelity",
            "--candidate",
            "fixtures/images/candidate-64x48.png",
            "--source",
            "fixtures/images/source-64x48.png",
        ])
        .output()
        .unwrap();
    assert_eq!(
        cli.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&cli.stderr)
    );
    let cli: Value = serde_json::from_slice(&cli.stdout).unwrap();
    assert_eq!(cli["session_id"], Value::Null, "{cli}");
    check(
        "estimate-cli.json",
        ESTIMATE_SCHEMA,
        &fix(&cli, &dir.join("runs"), "", &[]),
    );
}
