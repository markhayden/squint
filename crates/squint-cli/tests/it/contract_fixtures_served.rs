//! Tasks 8.6 and 9.10: squint's conformance fixtures from the `squint` binary (table-manners
//! 3.1, 4.3–4.6, 7 item 7): served runs with their session and correlation ids, the runs page,
//! the session, the refusals (a reused `client_run_id` with and without a run, `not_ready`, an
//! estimate's `invalid_arguments`), estimates allowed and refused for each reason (the command
//! line's too, with no session), and the runs only a server makes: stale estimates, `cap`,
//! `budget`, `credential`, and the run accepted under an id an earlier refusal released. An
//! estimate is never a run, so none of these is one. Generated by driving `squint serve` (and
//! `squint estimate` once), the machine values fixed, and held like the other fixtures: the
//! committed copy under `fixtures/contract/squint/` must equal what squint produces now;
//! `UPDATE_CONTRACT_FIXTURES=1` rewrites it after a deliberate change. Every server waits on what
//! it observes (a progress notification, a runs entry, a response), never on a sleep.
#![cfg(feature = "testkit")]
#![allow(clippy::unwrap_used)]

use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{Duration, Instant};

use serde_json::{Value, json};
use squint_testkit::mcp_client::{CallResult, Client, Failure};

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .unwrap()
}

fn out(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "squint-fixtures-served-{tag}-{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&dir);
    dir
}

/// `squint serve` on the minimal configuration and a provider script, writing under `out`.
fn server(out: &Path, script: &Path, overrides: &[&str]) -> Command {
    let mut c = Command::new(env!("CARGO_BIN_EXE_squint"));
    c.current_dir(repo_root())
        .args(["serve", "--config", "fixtures/config/minimal.toml"])
        .arg("--provider-script")
        .arg(script)
        .arg("--out")
        .arg(out);
    for o in overrides {
        c.args(["--set", o]);
    }
    c
}

/// A client of `command` whose roots hold the fixture images.
fn start(command: &mut Command) -> Client {
    let mut client = Client::start(command).unwrap();
    client.roots = vec![format!(
        "file://{}",
        repo_root().join("fixtures/images").display()
    )];
    client
}

fn script(name: &str) -> PathBuf {
    repo_root().join("fixtures/scripts").join(name)
}

fn client(out: &Path, name: &str, overrides: &[&str]) -> Client {
    start(&mut server(out, &script(name), overrides))
}

fn pair() -> Value {
    let image = |n: &str| json!({ "path": repo_root().join("fixtures/images").join(n) });
    json!({ "candidate": image("candidate-64x48.png"), "source": image("source-64x48.png") })
}

/// A document valid against one of the contract's schemas, by id.
fn valid(id: &str, doc: &Value) {
    struct Embedded;
    impl jsonschema::Retrieve for Embedded {
        fn retrieve(
            &self,
            uri: &jsonschema::Uri<String>,
        ) -> Result<Value, Box<dyn std::error::Error + Send + Sync>> {
            let (_, text) = table_manners::SCHEMAS
                .iter()
                .find(|(id, _)| *id == uri.as_str())
                .ok_or("unknown schema")?;
            Ok(serde_json::from_str(text)?)
        }
    }
    let (_, text) = table_manners::SCHEMAS
        .iter()
        .find(|(schema, _)| *schema == id)
        .unwrap();
    let schema: Value = serde_json::from_str(text).unwrap();
    let validator = jsonschema::options()
        .with_retriever(Embedded)
        .build(&schema)
        .unwrap();
    let errors: Vec<String> = validator.iter_errors(doc).map(|e| e.to_string()).collect();
    assert!(errors.is_empty(), "{id}: {errors:?}\n{doc}");
}

/// The session id every fixture uses, as rascal's do.
const SESSION: &str = "00000000-0000-4000-8000-000000000001";
const CLIENT: &str = "table-manners/client_run_id";
const ESTIMATE: &str = "table-manners/estimate";
/// The time every fixture shows.
const TIME: &str = "2026-01-01T00:00:00.000Z";

/// `doc` with the machine values fixed: the output directory, the session id, then each
/// `(from, to)` in `names` (run ids, a scratch configuration directory), then times, durations,
/// versions, input identities, bindings and expiries.
fn fix(doc: &Value, out: &Path, session: &str, names: &[(String, String)]) -> Value {
    let mut text = doc.to_string();
    if let Ok(canonical) = out.canonicalize() {
        text = text.replace(&canonical.display().to_string(), "/runs");
    }
    text = text.replace(&out.display().to_string(), "/runs");
    if !session.is_empty() {
        text = text.replace(session, SESSION);
    }
    for (from, to) in names {
        text = text.replace(from.as_str(), to);
    }
    let mut doc: Value = serde_json::from_str(&text).unwrap();
    fn walk(v: &mut Value) {
        match v {
            Value::Object(map) => {
                for (key, value) in map.iter_mut() {
                    match key.as_str() {
                        "started" | "finished" | "expires" if value.is_string() => {
                            *value = TIME.into();
                        }
                        "duration_ms" => *value = 0.into(),
                        "input_identity" | "binding" | "config_identity" if value.is_string() => {
                            *value = format!("sha256:{}", "0".repeat(64)).into();
                        }
                        "tool" if value.get("version").is_some() => {
                            value["version"] = "0.0.0".into();
                        }
                        _ => walk(value),
                    }
                }
            }
            Value::Array(items) => items.iter_mut().for_each(walk),
            _ => {}
        }
    }
    walk(&mut doc);
    doc
}

/// `doc`, already fixed, checked against `schema` and held to the committed fixture `name`.
fn check(name: &str, schema: &str, doc: &Value) {
    valid(schema, doc);
    let path = repo_root().join("fixtures/contract/squint").join(name);
    let text = serde_json::to_string_pretty(doc).unwrap() + "\n";
    if std::env::var_os("UPDATE_CONTRACT_FIXTURES").is_some() {
        std::fs::write(&path, &text).unwrap();
    }
    assert_eq!(
        std::fs::read_to_string(&path).unwrap_or_default(),
        text,
        "{} drifted from what squint serves; review, then UPDATE_CONTRACT_FIXTURES=1 and copy to table-manners",
        path.display()
    );
}

const RESULT: &str = "urn:table-manners:core:result";
const REFUSAL: &str = "urn:table-manners:core:refusal";
const ESTIMATE_SCHEMA: &str = "urn:table-manners:core:estimate";

/// The refusal data of a JSON-RPC `-32602` error.
fn refusal(r: Result<CallResult, Failure>) -> Value {
    match r {
        Err(Failure::Rpc {
            code: -32602,
            data: Some(data),
            ..
        }) => data,
        other => panic!("expected a refusal, got {other:?}"),
    }
}

fn session_id(c: &mut Client) -> String {
    let session: Value =
        serde_json::from_str(&c.read_resource("squint://session").unwrap()).unwrap();
    session["id"].as_str().unwrap().to_string()
}

/// The estimate of a `source_fidelity` call with these arguments.
fn estimate(c: &mut Client, arguments: Value) -> Value {
    let r = c
        .call(
            "estimate",
            json!({ "action": "source_fidelity", "arguments": arguments }),
        )
        .unwrap();
    assert!(!r.is_error, "{r:?}");
    r.structured.unwrap()
}

/// A run's result with its run id named `name` and, for a stale estimate, the binding and
/// expiry its reason quotes fixed.
fn run(doc: &Value, out: &Path, session: &str, name: &str, estimate: Option<&Value>) -> Value {
    let mut names = vec![(doc["run"]["id"].as_str().unwrap().to_string(), name.into())];
    if let Some(e) = estimate {
        names.push((
            e["binding"].as_str().unwrap().into(),
            format!("sha256:{}", "0".repeat(64)),
        ));
        names.push((e["expires"].as_str().unwrap().into(), TIME.into()));
    }
    fix(doc, out, session, &names)
}

/// The runs list once it holds `count` runs and none is still running.
fn runs_once_ended(c: &mut Client, count: usize) -> Value {
    let started = Instant::now();
    loop {
        let runs: Value = serde_json::from_str(&c.read_resource("squint://runs").unwrap()).unwrap();
        let entries = runs["runs"].as_array().unwrap();
        if entries.len() == count && entries.iter().all(|r| r["status"] != "running") {
            return runs;
        }
        assert!(
            started.elapsed() < Duration::from_secs(30),
            "runs never ended: {runs}"
        );
    }
}

/// The first progress notification for `token`, which comes once its request is accepted and
/// its id claimed. `waiting` also waits for the message that says the run sits in a retry wait.
fn progress(c: &mut Client, token: &str, waiting: bool) {
    loop {
        let n = c.next_notification().unwrap();
        if n["params"]["progressToken"] == token
            && (!waiting
                || n["params"]["message"]
                    .as_str()
                    .is_some_and(|m| m.starts_with("waiting")))
        {
            return;
        }
    }
}

/// A check waiting on a retry holds the permit; a second request queues behind it. While it
/// waits, its id is refused with no run (`refusal-no-run.json`); cancelled before its allocation,
/// its id stays claimed and is still refused with no run
/// (`refusal-cancelled-before-allocation.json`). The waiting check is cancelled during its retry
/// wait, so its failed attempt is unresolved spend; a reused id of it is refused with that run.
#[test]
fn the_served_correlation_fixtures_are_what_squint_serves() {
    let out = out("correlation");
    let mut c = client(&out, "slow-retry.json", &[]);
    let session = session_id(&mut c);

    let running = c
        .start_call_with_meta(
            "source_fidelity",
            pair(),
            json!({ "progressToken": "a", CLIENT: "host-attempt-1" }),
        )
        .unwrap();
    progress(&mut c, "a", true);
    let queued = c
        .start_call_with_meta(
            "source_fidelity",
            pair(),
            json!({ "progressToken": "q", CLIENT: "host-attempt-2" }),
        )
        .unwrap();
    progress(&mut c, "q", false);
    let no_run = refusal(c.call_with_meta(
        "source_fidelity",
        pair(),
        json!({ CLIENT: "host-attempt-2" }),
    ));
    // The server reads the two cancellations in order: once the running check's run has ended,
    // the queued request, cancelled first, has given up its wait with no run.
    c.cancel(queued).unwrap();
    c.cancel(running).unwrap();
    let runs = runs_once_ended(&mut c, 1);
    assert_eq!(runs["runs"][0]["status"], "cancelled", "{runs}");
    let cancelled = runs["runs"][0]["id"].as_str().unwrap().to_string();
    let cancelled_before = refusal(c.call_with_meta(
        "source_fidelity",
        pair(),
        json!({ CLIENT: "host-attempt-2" }),
    ));
    assert!(cancelled_before["run"].is_null(), "{cancelled_before}");
    let earlier = refusal(c.call_with_meta(
        "source_fidelity",
        pair(),
        json!({ CLIENT: "host-attempt-1" }),
    ));
    let served: Value = serde_json::from_str(
        &c.read_resource(&format!("squint://run/{cancelled}/run.json"))
            .unwrap(),
    )
    .unwrap();
    let runs: Value = serde_json::from_str(&c.read_resource("squint://runs").unwrap()).unwrap();
    let state: Value = serde_json::from_str(&c.read_resource("squint://session").unwrap()).unwrap();

    let names = [(cancelled, "served-cancelled".to_string())];
    for (name, doc, schema) in [
        ("run-served-cancelled-unresolved.json", &served, RESULT),
        ("runs.json", &runs, "urn:table-manners:core:runs"),
        ("session.json", &state, "urn:table-manners:core:session"),
        ("refusal-earlier-run.json", &earlier, REFUSAL),
        ("refusal-no-run.json", &no_run, REFUSAL),
        (
            "refusal-cancelled-before-allocation.json",
            &cancelled_before,
            REFUSAL,
        ),
    ] {
        check(name, schema, &fix(doc, &out, &session, &names));
    }
}

/// One ready server on the free scripted provider: an estimate allowed and one over the call's
/// cap; a call made on its estimate with a changed image and with a changed argument (stale);
/// a call whose `max_spend_usd` is below its envelope (`cap`); an estimate's wrong request (the
/// `invalid_arguments` refusal); and an id refused for an unknown argument, then accepted. A
/// second server is another session: the first's binding is stale there, which also stands for a
/// changed configuration (squint's configuration is the session's, 4.6).
#[test]
fn the_served_estimate_fixtures_are_what_squint_serves() {
    let out = out("estimates");
    let mut c = client(&out, "held.json", &[]);
    let session = session_id(&mut c);

    let allowed = estimate(&mut c, pair());
    assert_eq!(allowed["allowed"], true, "{allowed}");
    check(
        "estimate-allowed.json",
        ESTIMATE_SCHEMA,
        &fix(&allowed, &out, &session, &[]),
    );
    let mut low = pair();
    low["max_spend_usd"] = json!(0.000001);
    let capped = estimate(&mut c, low.clone());
    assert_eq!(capped["refused"], "cap", "{capped}");
    check(
        "estimate-refused-cap.json",
        ESTIMATE_SCHEMA,
        &fix(&capped, &out, &session, &[]),
    );

    let mut other_image = pair();
    other_image["candidate"] =
        json!({ "path": repo_root().join("fixtures/images/exif-rotated-64x48.png") });
    let mut briefed = pair();
    briefed["brief"] = json!("keep the sky");
    for (name, arguments) in [
        ("run-stale-estimate-image.json", other_image),
        ("run-stale-estimate-argument.json", briefed),
    ] {
        let r = c
            .call_with_meta(
                "source_fidelity",
                arguments,
                json!({ ESTIMATE: &allowed["binding"] }),
            )
            .unwrap()
            .structured
            .unwrap();
        assert_eq!(r["error"]["code"], "stale_estimate", "{r}");
        let id = name.trim_start_matches("run-").trim_end_matches(".json");
        check(name, RESULT, &run(&r, &out, &session, id, Some(&allowed)));
    }

    let r = c.call("source_fidelity", low).unwrap().structured.unwrap();
    assert_eq!(r["error"]["code"], "cap", "{r}");
    check(
        "run-cap.json",
        RESULT,
        &run(&r, &out, &session, "cap", None),
    );

    let mut over = pair();
    over["max_spend_usd"] = json!(5.0);
    let wrong = refusal(c.call(
        "estimate",
        json!({ "action": "source_fidelity", "arguments": over }),
    ));
    assert_eq!(wrong["reason"], "invalid_arguments", "{wrong}");
    check(
        "refusal-invalid-arguments.json",
        REFUSAL,
        &fix(&wrong, &out, &session, &[]),
    );

    let mut unknown = pair();
    unknown["colour"] = json!("blue");
    let first = c.call_with_meta("source_fidelity", unknown, json!({ CLIENT: "fix-1" }));
    assert!(
        matches!(first, Err(Failure::Rpc { code: -32602, .. })),
        "{first:?}"
    );
    let accepted = c
        .call_with_meta("source_fidelity", pair(), json!({ CLIENT: "fix-1" }))
        .unwrap()
        .structured
        .unwrap();
    assert_eq!(accepted["status"], "completed", "{accepted}");
    check(
        "run-accepted-after-refusal.json",
        RESULT,
        &run(&accepted, &out, &session, "accepted-after-refusal", None),
    );

    let second_out = out.join("second");
    let mut second = client(&second_out, "held.json", &[]);
    let second_session = session_id(&mut second);
    let r = second
        .call_with_meta(
            "source_fidelity",
            pair(),
            json!({ ESTIMATE: &allowed["binding"] }),
        )
        .unwrap()
        .structured
        .unwrap();
    assert_eq!(r["error"]["code"], "stale_estimate", "{r}");
    check(
        "run-stale-estimate-session.json",
        RESULT,
        &run(
            &r,
            &second_out,
            &second_session,
            "stale-estimate-session",
            Some(&allowed),
        ),
    );
}

